    <h2 class="text-3xl">From Natural History to Earth Sciences</h2>
    <p class="my-4">
      As scientific understanding advanced, geology gradually emerged from natural history as a distinct academic discipline.
    </p>
    <p class="my-4">
      In the early twentieth century, geology became increasingly distinct within UNB's curriculum. The Department of Geology and Mineralogy was formally established in 1941, later becoming the Department of Geology and, in 2012, the Department of Earth Sciences.
    </p>
    <p class="my-4">
      Throughout these changes, geological specimens remained important resources for teaching and research. Generations of professors, researchers, students, professional geologists, and collectors contributed to the collections through fieldwork, scientific investigations, and donations.
    </p>
    <p class="my-4">
      The collections grew to include specimens from New Brunswick, elsewhere in Canada, and around the world, documenting geological processes, mineral resources, ancient environments, and the history of life on Earth.
    </p>
    <p class="my-4">
      They also preserve the history of geological exploration itself. Original specimen labels, collection records, and associated documentation can reveal where specimens were found, who collected them, and how geological knowledge has changed over time.
    </p>
  </section>

  <section class="my-8 md:text-xl flow-root">
    <h2 class="text-3xl">Dr. Arnold L. McAllister (1921–2010): A Lasting Legacy</h2>
    <p class="my-4 italic">
      Geologist, educator, mentor, and dedicated steward of UNB's geological heritage
    </p>

    <figure class="mx-auto my-6 w-3/4 max-w-sm md:mx-0 md:my-0 md:mb-4 md:mt-1 md:max-w-none md:float-right md:clear-right md:ml-6 md:w-1/4">
