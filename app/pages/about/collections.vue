    <p class="my-4">
      Robb was a passionate advocate for scientific education and believed that students should learn by examining the natural world directly. He conducted geological expeditions throughout New Brunswick and produced a geological map of the province in 1849, contributing to the growing understanding of its natural resources.
    </p>
    <p class="my-4">
      In 1847, Robb and his colleague William Brydone-Jack appealed to the college administration for scientific equipment and the establishment of a museum. They argued that understanding Earth's history required students to examine the rocks, minerals, and fossils that preserved evidence of its past.
    </p>
    <p class="my-4">
      Despite limited funding, Robb began assembling the university's natural history collections through his own fieldwork and exchanges with other collectors. By the 1850s, the foundations of a geological museum had been established.
    </p>
    <p class="my-4">
      His dedication extended beyond the university. Through public lectures, scientific investigations, and work related to agriculture and natural resources, Robb helped demonstrate the practical value of science to New Brunswick society.
    </p>
    <p class="my-4">
      Robb established a tradition of learning through geological specimens and field observation that continues at UNB today.
    </p>
