        Professor of Geology (1921–2010)
      </figcaption>
    </figure>
    <p class="my-4">
      Dr. Arnold Lloyd McAllister, known affectionately as Arnie, helped shape UNB’s Department of Geology through research, teaching, mentorship, and stewardship of its collections.
    </p>
    <p class="my-4">
      A UNB geology graduate (1943), McAllister earned his PhD from McGill University in 1950 before working as a research scientist in Sudbury, Ontario. He subsequently returned to UNB, where he devoted much of his professional life to geological research, teaching, and the growth of the department.
    </p>
    <p class="my-4">
      As Department Chair from 1962 to 1971, McAllister guided a period of significant expansion in faculty and facilities. An internationally respected economic geologist, he made important contributions to understanding mineral deposits, particularly volcanic massive sulphide deposits, helping advance mineral exploration in New Brunswick and beyond.
    </p>
    <p class="my-4">
      McAllister was equally committed to teaching. He valued direct observation, field experience, and thoughtful questioning, inspiring students who would pursue careers in geoscience across Canada and beyond. McAllister’s influence is reflected in the achievements and generosity of other UNB alumni. Contributions associated with William Luff, Robert Quartermain, and Derek McBride have strengthened geological collections, educational opportunities, and support for students.
    </p>
    <p class="my-4">
      One particularly revealing example is Dr. W. Ernest Hale (1927–1986). In a memorial published by the Geological Society of America, McAllister recalled Hale as a lively, questioning student in his introductory geology class. Hale later joined UNB’s faculty in 1955, became a respected professor of economic and mining geology, and helped develop the university’s geological engineering program. His work in mineral exploration took him around the world, but McAllister especially remembered his generosity toward students and his ability to encourage them to achieve more than they thought possible. Their relationship, from teacher and student to colleagues, illustrates the lasting influence of mentorship in UNB’s geological community.
    </p>

    <p class="my-4">
      His legacy is also preserved in UNB's geological collections. McAllister devoted considerable care to documenting and organizing geological materials, leaving behind detailed handwritten specimen notes and records. These documents remain invaluable to the Quartermain Earth Science Centre today, helping us identify specimens, reconstruct collection histories, and preserve scientific information that might otherwise have been lost.
    </p>
    <p class="my-4">
      His careful documentation illustrates an enduring principle of collections care: a specimen’s value depends not only on the object itself, but also on the observations and context recorded with it.
    </p>
    <p class="my-4">
      Through his scholarship, mentorship, and dedication to preserving geological knowledge, McAllister left a legacy that remains visible in UNB’s collections and in the people who continue to study them.
    </p>
