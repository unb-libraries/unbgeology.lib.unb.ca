    <p class="my-4">
      After Robb’s death in 1861, Dr. Loring Woart Bailey joined UNB as Professor of Chemistry and Natural Science at only 21 years of age.
    </p>
    <p class="my-4">
      Educated at Harvard, Bailey brought new scientific connections and a strong commitment to field-based research. He explored the geology of New Brunswick and neighbouring regions, collaborated with prominent geologists, and contributed to the Geological Survey of Canada.
    </p>
    <p class="my-4">
      Bailey also continued Robb's efforts to build a university museum. Despite limited financial resources, he expanded the collections through fieldwork, donations, and specimen exchanges with leading scientific institutions, including Harvard, Yale, and the Smithsonian Institution.
    </p>
    <p class="my-4">
      By the 1870s, the museum contained extensive collections of minerals, fossils, plants, and animals. Its geological holdings were particularly important for documenting the natural history of New Brunswick and the broader Acadian region.
    </p>
    <p class="my-4">
      Bailey believed that a well-organized museum was essential for scientific education. He advocated for systematic classification and careful preservation, recognizing that collections should serve both current students and future generations. His vision extended beyond the classroom: the museum was intended to be a lasting repository of the province's natural heritage.
    </p>
    <p class="my-4">
      The specimens and historical records preserved today reflect Bailey’s vision: a collection that connects nineteenth-century exploration with future research, education, and stewardship.
    </p>

